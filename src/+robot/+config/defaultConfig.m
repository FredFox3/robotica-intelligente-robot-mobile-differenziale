function cfg = defaultConfig()
%DEFAULTCONFIG Return the configurable model, planning and control defaults.
%   R is the common wheel radius [m]; D is the full wheel separation [m].
%   Values are design choices, not parameters assigned by the official brief.
%   No simulation is run and no files are written.

    cfg.robot = struct('r', 0.05, 'd', 0.30);
    cfg.integration = struct('dt', 0.02); % Suggested RK4 step [s].
    cfg.robot.bodyRadius = 0.22; % Disc enclosing the complete robot [m].
    cfg.limits = struct('wheel', 10, 'v', 0.30, 'omega', 1.50);
    cfg.geometry = struct('margin', 0.03, 'tolerance', 1e-9, ...
        'maxSpatialStep', 0.01, 'maxDepth', 12);
    cfg.planning = struct('seed', 17, 'maxIterations', 10000, ...
        'maxSampleAttempts', 100, 'numCandidates', 24, 'goalBias', 0.15, ...
        'durationRange', [0.15, 0.80], 'headingWeight', 0.35, ...
        'connectDistance', 1.0, 'duplicateDistance', 0.001, ...
        'duplicateAngle', 0.001, 'goalPositionTolerance', 1e-8, ...
        'goalAngleTolerance', 1e-8, 'sampleDistance', 0.05, ...
        'sampleAngle', 0.05);
    cfg.control = struct('kRho', 0.8, 'kAlpha', 2, 'kTheta', 2, ...
        'alignEnter', 0.35, 'alignExit', 0.10, 'waypointTolerance', 0.01, ...
        'rotationTolerance', 0.01, 'goalPositionTolerance', 0.03, ...
        'goalAngleTolerance', 0.035);
    % Dense proportional waypoint tracking is slower than nominal RRT timing.
    cfg.simulation = struct('maxTime', 900, 'maxSteps', 45000, ...
        'maxTrackingError', 0.05, 'positionRoundoff', 1e-8, ...
        'angleRoundoff', 1e-10);
end
